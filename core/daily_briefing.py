def _fallback_brief(data: Dict, sections: List[str]) -> str:
    """Plain text fallback if LLM fails."""
    date = data.get("date", datetime.now().strftime("%A, %B %d, %Y"))
    lines = [f"Morning brief for {date}:", ""]
    lines.extend(sections)
    return "\n".join(lines)


