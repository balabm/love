"""
LOVE Daily Briefing System

Every morning at a configured time (default 08:00), LOVE assembles a rich
briefing from ALL connected sources and delivers it as a proactive notification.

Sources aggregated:
  - Google Calendar: today's events, free slots
  - Outlook/Teams: unread emails, calendar, presence
  - Finance: BTC/ETH prices, any overnight moves
  - GitHub: notifications, PR activity
  - System: battery, active process
  - Goals: active goals, recent progress
  - Memory: anything important from yesterday

The brief is generated by the LLM in LOVE's warm/direct voice — not a generic
dashboard dump. Each section ends with a proactive suggestion.
"""

