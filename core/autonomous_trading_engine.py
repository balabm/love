    # ─── Main Loop ───────────────────────────────────────────────────────────

    def start(self):
        if self._running:
            return
        self._running = True

        t1 = threading.Thread(target=self._generation_loop, daemon=True, name="ATE-Generate")
        t2 = threading.Thread(target=self._paper_trade_loop, daemon=True, name="ATE-PaperTrade")
        self._threads = [t1, t2]
        for t in self._threads:
            t.start()
        print("[AutonomousTradingEngine] Started. Will generate strategies, backtest, and paper-trade autonomously.")

    def stop(self):
        self._running = False
        self._save_strategies()

    def _generation_loop(self):
        """Generate new strategies and evolve existing ones."""
        time.sleep(60)  # Let system settle
        while self._running:
            try:
                now = time.time()
                if now - self._last_generate_time > AUTO_GENERATE_INTERVAL * 60:
                    self._last_generate_time = now

                    # Generate new strategy
                    strategy = self._generate_strategy()
                    if strategy:
                        result = self._auto_backtest(strategy)
                        if "error" not in result:
                            self._strategies.append(strategy)
                            self._save_strategies()
                            print(f"[ATE] Generated strategy '{strategy.name}' — return: {result['total_return_pct']:.1f}%, trades: {result['total_trades']}, win_rate: {result['win_rate']:.1f}%")

                            # Push to user if it's good
                            if result["total_return_pct"] > 5 and PUSH_AVAILABLE:
                                try:
                                    get_push_engine().push(
                                        "INSIGHT",
                                        f"🧠 New trading idea: '{strategy.name}' backtested at +{result['total_return_pct']:.1f}% return. Strategy: {strategy.description[:80]}",
                                        priority="normal",
                                        metadata={"source": "autonomous_trading", "strategy": strategy.id},
                                    )
                                except Exception as e:
                                    from core.execution_guard import log_error
                                    log_error(e, module="core.autonomous_trading_engine")

                    # Evolve existing
                    if len(self._strategies) >= 3:
                        evolved = self._evolve_strategies()
                        if evolved:
                            print(f"[ATE] Evolved strategy '{evolved.name}' — score: {evolved.score:.1f}")

                time.sleep(60)
            except Exception as e:
                print(f"[ATE] Generation loop error: {e}")
                time.sleep(300)

    def _paper_trade_loop(self):
        """Run top strategy in paper trading."""
        time.sleep(120)
        while self._running:
            try:
                now = time.time()
                if now - self._last_paper_trade_time > AUTO_PAPER_TRADE_INTERVAL * 60:
                    self._last_paper_trade_time = now
                    self._auto_paper_trade()
                time.sleep(60)
            except Exception as e:
                print(f"[ATE] Paper trade loop error: {e}")
                time.sleep(300)

    # ─── Persistence ─────────────────────────────────────────────────────────

    def _save_strategies(self):
        try:
            data = [s.to_dict() for s in self._strategies]
            GENERATED_STRATEGIES_DB.write_text(json.dumps(data, indent=2), encoding="utf-8")
        except Exception as e:
            from core.execution_guard import log_error
            log_error(e, module="core.autonomous_trading_engine")

    def _load_strategies(self):
        if not GENERATED_STRATEGIES_DB.exists():
            return
        try:
            data = json.loads(GENERATED_STRATEGIES_DB.read_text(encoding="utf-8"))
            for s in data:
                try:
                    self._strategies.append(GeneratedStrategy.from_dict(s))
                except Exception as e:
                    from core.execution_guard import log_error
                    log_error(e, module="core.autonomous_trading_engine")
        except Exception as e:
            from core.execution_guard import log_error
            log_error(e, module="core.autonomous_trading_engine")

    # ─── Public API ──────────────────────────────────────────────────────────

    def get_strategies(self) -> List[Dict]:
        return [s.to_dict() for s in reversed(self._strategies)]

    def get_top_strategy(self) -> Optional[Dict]:
        active = [s for s in self._strategies if s.score > 0]
        if not active:
            return None
        return max(active, key=lambda s: s.score).to_dict()

    def get_evolution_log(self, limit: int = 20) -> List[Dict]:
        if not STRATEGY_EVOLUTION_LOG.exists():
            return []
        try:
            lines = STRATEGY_EVOLUTION_LOG.read_text(encoding="utf-8").strip().split("\n")
            return [json.loads(line) for line in lines[-limit:] if line.strip()]
        except Exception:
            return []

    def get_auto_trade_log(self, limit: int = 20) -> List[Dict]:
        if not AUTO_TRADE_LOG.exists():
            return []
        try:
            lines = AUTO_TRADE_LOG.read_text(encoding="utf-8").strip().split("\n")
            return [json.loads(line) for line in lines[-limit:] if line.strip()]
        except Exception:
            return []

    def force_generate(self) -> Dict:
        """Manually trigger strategy generation."""
        strategy = self._generate_strategy()
        if not strategy:
            return {"success": False, "error": "Generation failed"}
        result = self._auto_backtest(strategy)
        if "error" in result:
            return {"success": False, "error": result["error"]}
        self._strategies.append(strategy)
        self._save_strategies()
        return {"success": True, "strategy": strategy.to_dict(), "backtest": result}

    def force_paper_trade(self) -> Dict:
        """Manually trigger auto paper trade."""
        self._auto_paper_trade()
        return {"success": True, "message": "Auto paper trade executed"}

    def get_status(self) -> Dict:
        return {
            "running": self._running,
            "strategies_generated": len(self._strategies),
            "last_generate_minutes_ago": round((time.time() - self._last_generate_time) / 60, 1),
            "last_paper_trade_minutes_ago": round((time.time() - self._last_paper_trade_time) / 60, 1),
            "top_strategy": self.get_top_strategy(),
        }


