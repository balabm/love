    # ─── Auto-Backtest ───────────────────────────────────────────────────────

    def _auto_backtest(self, strategy: GeneratedStrategy) -> Dict:
        """Run backtest on a generated strategy automatically."""
        executor = StrategyExecutor(strategy)
        if not executor.compile():
            return {"error": "Compilation failed"}

        # Fetch data
        candles = self._fetch_klines("BTC-USDT", "1h", 500)
        if not candles or len(candles) < 50:
            return {"error": "No data"}

        balance = 10000.0
        position = 0.0
        avg_entry = 0.0
        trades = []
        equity = []

        for i in range(30, len(candles)):
            window = candles[:i + 1]
            signal = executor.run(window)
            price = float(window[-1][4])

            if signal == "BUY" and position == 0:
                qty = (balance * 0.95) / price
                fee = qty * price * 0.001
                position = qty
                avg_entry = price
                balance -= qty * price + fee
                trades.append({"side": "BUY", "price": price, "qty": qty, "fee": fee})
            elif signal == "SELL" and position > 0:
                fee = position * price * 0.001
                balance += position * price - fee
                pnl = (price - avg_entry) * position
                trades.append({"side": "SELL", "price": price, "qty": position, "fee": fee, "pnl": pnl})
                position = 0
                avg_entry = 0

            total = balance + (position * price)
            equity.append(total)

        final_price = float(candles[-1][4])
        final_value = balance + (position * final_price)
        ret_pct = ((final_value / 10000) - 1) * 100
        wins = sum(1 for t in trades if t.get("pnl", 0) > 0)
        losses = sum(1 for t in trades if t.get("pnl", 0) < 0)
        total_trades = len([t for t in trades if t["side"] == "SELL"])
        win_rate = (wins / total_trades * 100) if total_trades > 0 else 0

        # Sharpe estimate (simplified)
        if len(equity) > 2:
            returns = [(equity[i] - equity[i-1]) / equity[i-1] for i in range(1, len(equity))]
            mean_ret = sum(returns) / len(returns)
            variance = sum((r - mean_ret) ** 2 for r in returns) / len(returns)
            sharpe = (mean_ret / (variance ** 0.5)) * (252 ** 0.5) if variance > 0 else 0
        else:
            sharpe = 0

        result = {
            "symbol": "BTC-USDT", "interval": "1h", "initial_balance": 10000,
            "final_value": round(final_value, 2), "total_return_pct": round(ret_pct, 2),
            "total_trades": total_trades, "win_rate": round(win_rate, 1),
            "sharpe": round(sharpe, 2), "trades": len(trades),
            "timestamp": datetime.now().isoformat(),
        }

        strategy.backtests.append(result)
        strategy.best_return = max(strategy.best_return, ret_pct)
        strategy.win_rate = win_rate
        strategy.total_trades = total_trades
        strategy.sharpe_estimate = sharpe
        strategy.status = "backtested"

        # Composite score: return * 0.5 + sharpe * 10 + win_rate * 0.2
        strategy.score = (ret_pct * 0.5) + (sharpe * 10) + (win_rate * 0.2)

        return result

