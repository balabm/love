    def _extract_json_from_response(self, text: str) -> dict | None:
        """Robustly extract JSON from LLM text, handling markdown and partial output."""
        if not text:
            return None

        def _try_parse(candidate: str):
            """Try to parse JSON, with aggressive repair for small-model output."""
            if not candidate:
                return None
            # Strip common LLM artifacts
            candidate = candidate.strip()
            # Strip <thinking> / reasoning tags
            candidate = re.sub(r"<think>.*?</think>", "", candidate, flags=re.DOTALL)
            candidate = re.sub(r"<thinking>.*?</thinking>", "", candidate, flags=re.DOTALL)
            candidate = re.sub(r"\[thinking\].*?\[/thinking\]", "", candidate, flags=re.DOTALL)
            if not candidate:
                return None
            # 1. Direct parse
            try:
                return json.loads(candidate)
            except Exception:
                pass  # expected when LLM returns non-JSON prose
            # 2. Remove trailing commas before } or ]
            repaired = re.sub(r',(\s*[}\]])', r'\1', candidate)
            # 3. Replace single-quoted string keys/values with double quotes (simple cases)
            repaired = re.sub(r"(?<=[{\s,])([a-zA-Z_][a-zA-Z0-9_]*)(?=\s*:)", r'"\1"', repaired)
            try:
                return json.loads(repaired)
            except Exception:
                pass  # repair also failed — expected
            return None

        # 1. Direct parse
        direct = _try_parse(text)
        if direct:
            return direct

        # 2. Markdown code block
        patterns = [
            r'```json\s*([\s\S]*?)\s*```',
            r'```\s*([\s\S]*?)\s*```',
        ]
        for pattern in patterns:
            match = re.search(pattern, text)
            if match:
                parsed = _try_parse(match.group(1).strip())
                if parsed:
                    return parsed

        # 3. Find outermost braces by balancing
        brace_depth = 0
        best_start = -1
        best_end = -1
        for i, ch in enumerate(text):
            if ch == '{':
                if brace_depth == 0:
                    best_start = i
                brace_depth += 1
            elif ch == '}':
                brace_depth -= 1
                if brace_depth == 0 and best_start != -1:
                    best_end = i
                    parsed = _try_parse(text[best_start:best_end + 1])
                    if parsed:
                        return parsed

        # 4. Fallback: first-to-last braces
        start = text.find('{')
        end = text.rfind('}')
        if start != -1 and end > start:
            parsed = _try_parse(text[start:end + 1])
            if parsed:
                return parsed

        return None

