class GeneratedStrategy:
    """A strategy generated by the LLM with metadata and performance tracking."""

    def __init__(self, name: str, description: str, logic_type: str, params: Dict,
                 code: str = "", generation_prompt: str = ""):
        self.id = f"gen_{int(time.time())}_{random.randint(1000, 9999)}"
        self.name = name
        self.description = description
        self.logic_type = logic_type  # e.g. "momentum", "mean_reversion", "breakout"
        self.params = params
        self.code = code
        self.generation_prompt = generation_prompt
        self.created_at = datetime.now().isoformat()
        self.backtests: List[Dict] = []
        self.paper_trades: List[Dict] = []
        self.status = "generated"  # generated -> backtested -> active -> retired
        self.score = 0.0  # composite score
        self.best_return = 0.0
        self.win_rate = 0.0
        self.total_trades = 0
        self.sharpe_estimate = 0.0

    def to_dict(self) -> Dict:
        return {
            "id": self.id, "name": self.name, "description": self.description,
            "logic_type": self.logic_type, "params": self.params, "code": self.code,
            "generation_prompt": self.generation_prompt, "created_at": self.created_at,
            "backtests": self.backtests, "paper_trades": self.paper_trades,
            "status": self.status, "score": self.score, "best_return": self.best_return,
            "win_rate": self.win_rate, "total_trades": self.total_trades,
            "sharpe_estimate": self.sharpe_estimate,
        }

    @classmethod
    def from_dict(cls, data: Dict) -> "GeneratedStrategy":
        s = cls(data["name"], data["description"], data.get("logic_type", "unknown"),
                data.get("params", {}), data.get("code", ""), data.get("generation_prompt", ""))
        s.id = data["id"]
        s.created_at = data.get("created_at", datetime.now().isoformat())
        s.backtests = data.get("backtests", [])
        s.paper_trades = data.get("paper_trades", [])
        s.status = data.get("status", "generated")
        s.score = data.get("score", 0.0)
        s.best_return = data.get("best_return", 0.0)
        s.win_rate = data.get("win_rate", 0.0)
        s.total_trades = data.get("total_trades", 0)
        s.sharpe_estimate = data.get("sharpe_estimate", 0.0)
        return s


class StrategyExecutor:
    """Executes generated strategy code safely."""

    def __init__(self, strategy: GeneratedStrategy):
        self.strategy = strategy
        self._compiled = None
        self._state = {}

    def compile(self) -> bool:
        """Compile the generated strategy code."""
        if not self.strategy.code:
            return False
        try:
            # Wrap in a function that takes candles and returns signal
            code = self.strategy.code
            # If code is just logic, wrap it
            if "def on_data" not in code:
                code = f"""
_state = {{}}
{code}
def on_data(candles):
    import statistics
    closes = [float(c[4]) for c in candles]
    if len(closes) < 10:
        return "HOLD"
    return _strategy_logic(closes, _state)
"""
            # Compile safely
            self._compiled = compile(code, f"<strategy_{self.strategy.id}>", "exec")
            return True
        except Exception as e:
            print(f"[ATE] Strategy compilation failed for {self.strategy.id}: {e}")
            return False

    def run(self, candles: List[List]) -> str:
        """Run the strategy on candle data."""
        if self._compiled is None and not self.compile():
            return "HOLD"
        try:
            # Normalize params: convert string numbers to float/int,
            # and cast floats that are whole numbers back to int so list indexing works.
            raw_params = self.strategy.params or {}
            norm_params: Dict[str, Any] = {}
            for k, v in raw_params.items():
                if isinstance(v, str):
                    try:
                        if "." in v:
                            norm_params[k] = float(v)
                        else:
                            norm_params[k] = int(v)
                    except ValueError:
                        norm_params[k] = v
                elif isinstance(v, float) and v.is_integer():
                    norm_params[k] = int(v)
                else:
                    norm_params[k] = v

            def get_param(key: str, default=0.0):
                return norm_params.get(key, default)

            def get_int_param(key: str, default: int = 10) -> int:
                """Return param as int — safe for list indexing."""
                v = norm_params.get(key, default)
                try:
                    return int(float(v))
                except (TypeError, ValueError):
                    return int(default)

            def get_float_param(key: str, default: float = 0.0) -> float:
                """Return param as float."""
                v = norm_params.get(key, default)
                try:
                    return float(v)
                except (TypeError, ValueError):
                    return float(default)

            local_ns = {
                "candles": candles,
                "statistics": __import__("statistics"),
            }
            # Build globals for exec: include helpers AND inject each param
            # as a bare-name global so poorly-generated strategies that reference
            # param names directly (e.g., `trend_line_length`) still work.
            exec_globals = {
                "__builtins__": __builtins__,
                "params": norm_params,
                "get_param": get_param,
                "get_int_param": get_int_param,
                "get_float_param": get_float_param,
            }
            for k, v in norm_params.items():
                if k not in exec_globals:
                    exec_globals[k] = v
            exec(self._compiled, exec_globals, local_ns)
            on_data_fn = local_ns.get("on_data")
            if on_data_fn:
                return on_data_fn(candles)
            return "HOLD"
        except Exception as e:
            print(f"[ATE] Strategy execution error: {e}")
            return "HOLD"


